# ---------------------------------------------------------------------------
# 1. Filesystem mtimes (os.stat) of key provenance and data files
# ---------------------------------------------------------------------------
print("\n>>> 1. FILESYSTEM MTIMES (os.stat):")
target_files = [
    "provenance/seal_record.json",
    "provenance/stage4_plan.json",
    "sealed/hub_counts.h5ad",
    "audit/guard_audit.log",
    "results/tables/stage4_hub_genes_descriptive_summary.csv",
    "data/processed/GSE248762_stage4_unsealed_hubs_clean.h5ad"
]

stat_records = []
for fpath in target_files:
    if os.path.exists(fpath):
        st = os.stat(fpath)
        mtime_epoch = st.st_mtime
        mtime_utc = datetime.datetime.fromtimestamp(mtime_epoch, tz=datetime.timezone.utc).isoformat()
        mtime_local = datetime.datetime.fromtimestamp(mtime_epoch).isoformat()
        size_bytes = st.st_size
        stat_records.append({
            "File": fpath,
            "Size_Bytes": size_bytes,
            "Mtime_UTC": mtime_utc,
            "Mtime_Local": mtime_local,
            "Status": "EXISTS"
        })
    else:
        stat_records.append({
            "File": fpath,
            "Size_Bytes": None,
            "Mtime_UTC": None,
            "Mtime_Local": None,
            "Status": "NOT_FOUND"
        })

import pandas as pd
df_stat = pd.DataFrame(stat_records)
print(df_stat.to_string(index=False))

